import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
const executablePath = process.env.AI_BROWSER_EXECUTABLE ?? (process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : undefined);
const browser = await chromium.launch({ executablePath, headless: true });
try {
 const page = await browser.newPage();
 const errors = []; page.on('pageerror', error => errors.push(error.message));
 await page.goto(process.env.AI_DEMO_URL ?? 'http://127.0.0.1:8788/');
 await page.getByRole('button', { name: 'Run offline replay', exact: true }).click();
 await page.getByRole('status').filter({ hasText: 'Reference replay complete' }).waitFor();
 if (await page.locator('#actions .action').count() !== 2) throw new Error('Expected two action cards');
 const messageCard=page.locator('[data-proposal-kind="message"]');
 if(await messageCard.count()!==1 || await page.locator('[data-proposal-kind="task"]').count()!==2)throw new Error('Expected one message draft and two task proposals');
 const editedBody='Hi Cameron, could you share the LiveKit transcript format when it is ready?';
 await messageCard.getByLabel('Message body').fill(editedBody);
 await page.getByRole('button',{name:'Run offline replay',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Save or reset unsaved review edits'}).waitFor();
 await page.route('**/api/reviews/**/proposals/*',route=>route.abort('failed'));
 await messageCard.getByRole('button',{name:'Save edits',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Cannot reach the local demo server. Your unsaved edits are still here.'}).waitFor();
 if(await messageCard.getByLabel('Message body').inputValue()!==editedBody)throw new Error('Network failure lost the unsaved message');
 await page.unroute('**/api/reviews/**/proposals/*');
 await messageCard.getByRole('button',{name:'Save edits',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Edits saved.'}).waitFor();
 await messageCard.getByRole('button',{name:'Approve',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Approved locally.'}).waitFor();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export approved JSON',exact:true}).click();
 const download=await downloadPromise;
 const exported=JSON.parse(await readFile(await download.path(),'utf8'));
 if(exported.proposals.length!==1 || exported.proposals[0].body!==editedBody || exported.deliveryStatus!=='not_connected')throw new Error('Approved-only export was incorrect');
 await page.reload();
 await page.locator('#savedReviews option').first().waitFor({state:'attached'});
 await page.selectOption('#savedReviews',exported.id);
 await page.getByRole('button',{name:'Load saved review',exact:true}).click();
 await messageCard.getByLabel('Message body').waitFor();
 if(await messageCard.getByLabel('Message body').inputValue()!==editedBody)throw new Error('Saved message edit did not survive reload');
 await messageCard.getByText('approved',{exact:true}).waitFor();
 await messageCard.getByLabel('Message body').fill(editedBody+' Thanks!');
 await messageCard.getByRole('button',{name:'Save edits',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Edits saved.'}).waitFor();
 await messageCard.getByText('draft',{exact:true}).waitFor();
 if(!await page.getByRole('button',{name:'Export approved JSON',exact:true}).isDisabled())throw new Error('Editing an approved draft must require approval again');
 const taskCard=page.locator('[data-proposal-kind="task"]').first();
 await taskCard.getByRole('button',{name:'Discard',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Proposal discarded.'}).waitFor();
 await taskCard.getByRole('button',{name:'Restore',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Proposal restored as a draft.'}).waitFor();
 await page.selectOption('#reviewer','cameron');
 await page.getByRole('button',{name:'Run offline replay',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Reviewing as Cameron Boyle.'}).waitFor();
 if(await page.getByLabel('Message recipient').inputValue()!=='nathan')throw new Error('Reviewer selection did not change the generated message recipient');
 await page.selectOption('#fixture', 'tentative');
 await page.getByRole('button', { name: 'Run offline replay', exact: true }).click();
 await page.getByText('No committed actions extracted.').waitFor();
 await page.route('**/api/run', route => route.abort('failed'));
 await page.getByRole('button', { name: 'Run offline replay', exact: true }).click();
 await page.getByRole('status').filter({ hasText: 'Cannot reach the local demo server' }).waitFor();
 await page.unroute('**/api/run');
 let live = null;
 if (process.argv.includes('--live')) {
   const beforeUsage = await page.evaluate(() => fetch('/api/usage').then(r => r.json()));
   await page.selectOption('#fixture', 'commitments');
   await page.selectOption('#mode', 'live');
   const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/run') && r.request().method() === 'POST', { timeout: 45000 });
   await page.getByRole('button', { name: 'Extract with Gemini', exact: true }).click();
   const result = await (await responsePromise).json();
   if (result.status !== 'success') throw new Error('Live browser extraction failed: ' + result.error?.code);
   await page.getByRole('status').filter({ hasText: 'Draft ready for review' }).waitFor();
   if (await page.locator('#actions .action').count() !== 2) throw new Error('Expected two live action cards');
   const afterUsage = await page.evaluate(() => fetch('/api/usage').then(r => r.json()));
   if (!afterUsage.configured || afterUsage.today.attempts !== beforeUsage.today.attempts + 1) throw new Error('Live request was not recorded exactly once in the persistent usage meter');
   live = { model: result.model, actions: 2, latencyMs: result.latencyMs, usageTrackingVerified: true };
 }
 console.log(JSON.stringify({ browser: 'Chrome', replayActions: 2, tentativeActions: 0, connectionFailureHandled: true, reviewFlow: { messages: 1, tasks: 2, editApproveExportReload: true, editInvalidatesApproval: true, discardRestore: true, networkFailurePreservesEdits: true, reviewerSelection: true, unsavedEditsProtected: true }, live, pageErrors: errors }));
 if(errors.length) process.exitCode=1;
} finally { await browser.close(); }
